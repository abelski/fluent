"""Build data/grammar/adjectives.txt — adjective paradigms for grammar Basic options (#62f).

Usage: cd backend && .venv/bin/python scripts/build_adjective_paradigms.py

One line per adjective, tab-separated: the dictionary form (masc. nom. sg.) first, then
masc. sg, masc. pl, fem. sg, fem. pl — each in the 6 cases Vard, Kilm, Naud, Galin, Įnag, Viet.
Regular adjectives only; the declension type is read from the ending.
"""
from pathlib import Path

ADJECTIVES = """
geras blogas naujas senas jaunas mažas didelis šiltas šaltas karštas
ilgas trumpas baltas juodas raudonas mėlynas žalias geltonas pilkas rudas
gražus brangus pigus skanus sunkus lengvas švarus tylus ramus įdomus
patogus linksmas liūdnas greitas lėtas saldus platus siauras šviežias sveikas
""".split()

# Endings per type: masc sg, masc pl, fem sg, fem pl (Vard, Kilm, Naud, Galin, Įnag, Viet).
# "+" marks endings that start with i + vowel: before them t→č, d→dž (-us type).
TYPES = {
    "as": ("as o am ą u ame", "i ų iems us ais uose",
           "a os ai ą a oje", "os ų oms as omis ose"),
    "ias": ("ias io iam ią iu iame", "i ių iems ius iais iuose",
            "ia ios iai ią ia ioje", "ios ių ioms ias iomis iose"),
    "us": ("us aus +iam ų +iu +iame", "ūs +ių +iems +ius +iais +iuose",
           "i +ios +iai +ią +ia +ioje", "+ios +ių +ioms +ias +iomis +iose"),
    "is": ("is io iam į iu iame", "i ių iems ius iais iuose",
           "ė ės ei ę e ėje", "ės ių ėms es ėmis ėse"),
}


def paradigm(adj: str) -> list[str]:
    kind = next(k for k in ("ias", "as", "us", "is") if adj.endswith(k))
    stem = adj[: -len(kind)]
    forms = []
    for group in TYPES[kind]:
        for ending in group.split():
            s = stem
            if ending.startswith("+"):
                ending = ending[1:]
                if s.endswith("t"):
                    s = s[:-1] + "č"
                elif s.endswith("d"):
                    s = s[:-1] + "dž"
            forms.append(s + ending)
    return forms


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "data/grammar/adjectives.txt"
    lines = [
        "# Adjective paradigms for grammar Basic multiple choice (#62f).",
        "# Generated by scripts/build_adjective_paradigms.py — edit the script, not this file.",
        "# Column 1 = dictionary form; then masc sg, masc pl, fem sg, fem pl x 6 cases",
        "# (Vard, Kilm, Naud, Galin, Įnag, Viet).",
    ]
    lines += ["\t".join([a] + paradigm(a)) for a in ADJECTIVES]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(ADJECTIVES)} adjectives to {out}")


if __name__ == "__main__":
    assert paradigm("platus")[2] == "plačiam" and paradigm("platus")[12] == "plati"
    assert paradigm("saldus")[13] == "saldžios" and paradigm("didelis")[12] == "didelė"
    main()
